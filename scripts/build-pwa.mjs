import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { pathToFileURL } from "node:url";

export function serviceWorkerSource({ version, assets }) {
  return `// Generated by scripts/build-pwa.mjs. Only public static files are cached.
const CACHE = ${JSON.stringify(`music-challenge-static-${version}`)};
const ASSETS = ${JSON.stringify(assets)};
const ALLOWED = new Set(ASSETS);
const checks = new Map();
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)));
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('music-challenge-static-') && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('message', event => {
  if (event.data?.type === 'PWA_CLIENT_STATUS') {
    const check = checks.get(event.data.requestId);
    if (check && check.pending.has(event.source?.id)) {
      check.pending.delete(event.source.id);
      if (event.data.active) check.blocked = true;
      if (!check.pending.size) check.finish();
    }
  }
  if (event.data?.type === 'ACTIVATE_UPDATE') {
    event.waitUntil((async () => {
      const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      const requestId = String(Date.now()) + Math.random();
      const safe = await new Promise(resolve => {
        const check = { pending: new Set(clients.map(client => client.id)), blocked: false };
        let timer;
        check.finish = () => {
          clearTimeout(timer);
          checks.delete(requestId);
          resolve(!check.blocked && !check.pending.size);
        };
        checks.set(requestId, check);
        timer = setTimeout(check.finish, 2500);
        if (!clients.length) check.finish();
        for (const client of clients) client.postMessage({ type: 'PWA_UPDATE_QUERY', requestId });
      });
      if (safe) {
        for (const client of clients) client.postMessage({ type: 'PWA_UPDATE_APPROVED' });
        await self.skipWaiting();
      }
      else event.source?.postMessage({ type: 'PWA_UPDATE_BLOCKED' });
    })());
  }
});
self.addEventListener('fetch', event => {
  const request = event.request, url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname === '/api' || url.pathname.startsWith('/api/')) return;
  if (request.mode === 'navigate') {
    // HTML, admin, room invites and result routes are never stored in CacheStorage.
    event.respondWith(fetch(request).catch(async () => (await caches.open(CACHE)).match('/offline.html')));
    return;
  }
  if (url.search || !ALLOWED.has(url.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(url.pathname);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok && response.type !== 'opaque') await cache.put(url.pathname, response.clone());
    return response;
  })());
});
`;
}

export async function buildPWA(directory = "dist") {
  const files = (await readdir(path.join(directory, "assets")))
    .filter(
      (name) =>
        !name.startsWith("AdminPage-") &&
        /\.(?:js|css|woff2?|png|svg|webp)$/.test(name),
    )
    .map((name) => `/assets/${name}`);
  const assets = [
    ...files,
    "/offline.html",
    "/offline.css",
    "/manifest.webmanifest",
    "/images/music-challenge-mark.svg",
    "/icons/icon-192.png",
    "/icons/icon-512.png",
    "/icons/maskable-512.png",
    "/icons/apple-touch-icon.png",
  ].sort();
  const hash = createHash("sha256");
  // Changing this generator also changes the worker/cache version.
  hash.update(serviceWorkerSource.toString());
  for (const asset of assets) {
    hash.update(asset);
    hash.update(await readFile(path.join(directory, asset)));
  }
  const version = hash.digest("hex").slice(0, 16);
  await writeFile(
    path.join(directory, "sw.js"),
    serviceWorkerSource({ version, assets }),
  );
  return { version, assets };
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const { assets, version } = await buildPWA(process.argv[2] || "dist");
  console.log(`PWA ${version}: ${assets.length} public static assets`);
}
